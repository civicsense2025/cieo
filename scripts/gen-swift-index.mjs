#!/usr/bin/env node
// Lists every `struct X: MotionAtomView` under atoms/swift into AtomIndex.generated.swift.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'atoms/swift');
const names = [];
const walk = (d) => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name.endsWith('.swift') && !e.name.endsWith('.generated.swift')) {
      for (const m of fs.readFileSync(p, 'utf8').matchAll(/struct\s+(\w+)\s*:\s*MotionAtomView\b/g)) names.push(m[1]);
    }
  }
};
walk(dir);
names.sort();
const body = `// Generated by scripts/gen-swift-index.mjs. Do not edit.
import SwiftUI

public enum MotionAtoms {
    public static let all: [MotionAtom] = [
${names.map((n) => `        MotionAtom(${n}.self),`).join('\n')}
    ]
}
`;
fs.writeFileSync(path.join(dir, 'AtomIndex.generated.swift'), body);
console.log(`gen-swift-index: ${names.length} atoms`);
