#!/usr/bin/env node
// Deterministic, dependency-free exports. Run --check to detect drift without writing.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createTheme, brands, toCSS, toDTCG, toPortable, toNative, themeSchema } from '../design/index.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const files = new Map();
const json = (value) => JSON.stringify(value, null, 2) + '\n';
const put = (path, content) => files.set(path, content);
const base = createTheme();
put('design/generated/default.tokens.json', json(toDTCG(base)));
put('design/generated/default.portable.json', json(toPortable(base)));
put('design/theme.schema.json', json(themeSchema()));
for (const [target, extension] of Object.entries({ swift: 'swift', rust: 'rs', kotlin: 'kt', dart: 'dart', python: 'py', c: 'h' })) {
  put(`design/generated/CieoDesignTokens.${extension}`, toNative(base, target));
}
for (const brand of Object.keys(brands)) for (const scheme of ['light', 'dark']) for (const contrast of ['standard', 'high']) {
  const theme = createTheme({ brand, scheme, contrast });
  put(`design/generated/themes/${brand}-${scheme}${contrast === 'high' ? '-high' : ''}.css`, toCSS(theme));
}
const wrap = (condition, theme) => `@media (${condition}) {\n${toCSS(theme).replace(':root', ':root:not([data-cieo-theme])')}\n}\n`;
put('design/themes.css', '/* Generated by scripts/build-design.mjs. Application overrides belong in a separate stylesheet. */\n' + toCSS(base)
  + wrap('prefers-color-scheme: dark', createTheme({ scheme: 'dark' }))
  + wrap('prefers-contrast: more', createTheme({ contrast: 'high' }))
  + '@media (prefers-color-scheme: dark) {\n' + wrap('prefers-contrast: more', createTheme({ scheme: 'dark', contrast: 'high' })) + '}\n');
let failures = 0;
for (const [name, expected] of files) {
  const file = resolve(root, name);
  if (check) {
    let actual;
    try { actual = readFileSync(file, 'utf8'); } catch { actual = null; }
    if (actual !== expected) { console.error(`Stale generated file: ${name}`); failures += 1; }
  } else { mkdirSync(dirname(file), { recursive: true }); writeFileSync(file, expected); }
}
// The managed tree has an exact inventory, so removed exports cannot survive unnoticed.
const walk = (path) => readdirSync(path, { withFileTypes: true }).flatMap((entry) => {
  const child = resolve(path, entry.name);
  return entry.isDirectory() ? walk(child) : [relative(root, child).replaceAll('\\', '/')];
});
if (check) for (const name of walk(resolve(root, 'design/generated'))) {
  if (!files.has(name)) { console.error(`Unexpected generated file: ${name}`); failures += 1; }
}
if (failures) process.exitCode = 1;
else console.log(`design: ${files.size} exports ${check ? 'verified' : 'written'}`);
