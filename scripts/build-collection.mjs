#!/usr/bin/env node
// Builds the collection app page (docs/collection.html) from real recipes.
// --linked writes a small entry point for reviewable checked-in diffs; both use identical sources.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dir=path.join(root,'atoms/web');
const read=f=>fs.readFileSync(path.join(dir,f),'utf8');
const args=process.argv.slice(2),linked=args.includes('--linked');
const out=path.resolve(args.find(a=>!a.startsWith('--'))||path.join(root,'docs/collection.html'));
const blocks=JSON.parse(read('blocks.json'));
const styles=['tokens','shell','atoms','dialogs'].map(f=>`catalogue/${f}.css`);
const scripts=['runtime.core.js',...blocks,...['icons','isolation','appearance','navigation','gallery','dialogs','inspector'].map(f=>`catalogue/${f}.js`),'catalogue/runtime.js'];
const index=JSON.parse(read('index.json'));
const records=Array.isArray(index)?index:index.atoms;
const relative=f=>path.relative(path.dirname(out),path.join(dir,f)).split(path.sep).join('/');
const css=linked?styles.map(f=>`<link rel="stylesheet" href="${relative(f)}">`).join('\n'):`<style>\n${styles.map(read).join('\n')}\n</style>`;
const js=linked?`<script src="${relative('catalogue/boot.js')}"></script>`:`<script>\n${scripts.map(f=>`window.CIEO_SOURCE_HINT=${JSON.stringify(f)};\n${read(f)}`).join('\n').replace(/<\/script/gi,'<\\/script')}\n</script>`;
// Parallel classic-script downloads retain insertion order via async=false.
if(linked){
  const boot=`/* Generated by scripts/build-library.mjs; do not edit. */\n(() => {\n  const base=new URL('../',document.currentScript.src);\n  const sources=${JSON.stringify(scripts)};\n  for(const file of sources){\n    const script=document.createElement('script');script.async=false;script.src=new URL(file,base).href;\n    script.onerror=()=>{document.getElementById('collection-subtitle').textContent='A source file could not load. Open the standalone catalogue or serve the full checkout.'};\n    document.head.append(script);\n  }\n})();\n`;
  fs.writeFileSync(path.join(dir,'catalogue/boot.js'),boot);
}
const html=read('catalogue/shell.html').replace('<!-- CATALOGUE_STYLES -->',()=>css).replace('<!-- CATALOGUE_SCRIPTS -->',()=>js);
fs.mkdirSync(path.dirname(out),{recursive:true});fs.writeFileSync(out,html);
console.log(`build-library: ${blocks.length} source blocks, ${records.length} indexed recipes -> ${out} (${linked?'linked':'standalone'})`);
