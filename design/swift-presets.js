import { brands, grounds, radii, densities } from './presets.js';
import { createTheme } from './theme.js';
import { channels } from './color.js';

const rgbTuple = (hexValue) => channels(hexValue).map((c) => Number(c.toFixed(4))).join(', ');

function quad(getHex) {
  const ls = rgbTuple(getHex('light', 'standard'));
  const ds = rgbTuple(getHex('dark', 'standard'));
  const lh = rgbTuple(getHex('light', 'high'));
  const dh = rgbTuple(getHex('dark', 'high'));
  return `DynamicSRGB(ls: (${ls}), ds: (${ds}), lh: (${lh}), dh: (${dh}))`;
}

/** Generate Swift multi-brand, multi-ground, dynamic-appearance presets audited by createTheme(). */
export function toSwiftPresets() {
  const cache = new Map();
  const themeAt = (brand, ground, scheme, contrast) => {
    const key = `${brand}:${ground}:${scheme}:${contrast}`;
    if (!cache.has(key)) cache.set(key, createTheme({ brand, ground, scheme, contrast }));
    return cache.get(key);
  };

  const neutralRoles = [
    ['canvas', 'color-canvas'], ['surface', 'color-surface'], ['surfaceLow', 'color-surface-low'],
    ['surfaceHigh', 'color-surface-high'], ['raised', 'color-raised'], ['sunken', 'color-sunken'],
    ['text', 'color-text'], ['muted', 'color-muted'], ['subtle', 'color-subtle'],
    ['border', 'color-border'], ['borderStrong', 'color-border-strong'],
    ['success', 'color-success'], ['successSoft', 'color-success-soft'],
    ['warning', 'color-warning'], ['warningSoft', 'color-warning-soft'],
    ['danger', 'color-danger'], ['dangerSoft', 'color-danger-soft'],
    ['info', 'color-info'], ['infoSoft', 'color-info-soft'],
  ];

  const brandRoles = [
    ['accent', 'color-accent'], ['onAccent', 'color-on-accent'], ['accentHover', 'color-accent-hover'],
    ['accentSoft', 'color-accent-soft'], ['onAccentSoft', 'color-on-accent-soft'], ['selection', 'color-selection'],
  ];

  const groundCases = Object.keys(grounds).map((g) => {
    const props = neutralRoles.map(([swiftName, tokenName]) => (
      `${swiftName}: ${quad((s, c) => themeAt('studio', g, s, c).tokens[tokenName].value)}`
    ));
    const lines = [];
    for (let i = 0; i < props.length; i += 2) lines.push(`            ${props.slice(i, i + 2).join(', ')}`);
    return `        .${g}: GroundPalette(\n${lines.join(',\n')}\n        )`;
  }).join(',\n');

  const brandCases = [];
  for (const b of Object.keys(brands)) {
    for (const g of Object.keys(grounds)) {
      const props = brandRoles.map(([swiftName, tokenName]) => (
        `${swiftName}: ${quad((s, c) => themeAt(b, g, s, c).tokens[tokenName].value)}`
      ));
      const lines = [];
      for (let i = 0; i < props.length; i += 3) lines.push(`            ${props.slice(i, i + 3).join(', ')}`);
      brandCases.push(`        "${b}:${g}": BrandPalette(\n${lines.join(',\n')}\n        )`);
    }
  }

  const cornerCases = Object.entries(radii).map(([name, [small, control, surface]]) => (
    `        case .${name}: return (${small}.0, ${control}.0, ${surface}.0, 9999.0)`
  )).join('\n');

  const densityCases = Object.entries(densities).map(([name, h]) => (
    `        case .${name}: return (${Math.max(24, h - 12)}.0, ${h - 8}.0, ${h}.0, ${h + 8}.0, ${h + 12}.0)`
  )).join('\n');

  return `// Generated by scripts/build-design.mjs from Cieo's audited 4-tier token graph. Do not hand-edit.
import SwiftUI
#if canImport(UIKit)
import UIKit
#elseif canImport(AppKit)
import AppKit
#endif

public enum ThemeBrand: String, CaseIterable, Sendable {
    case studio, iris, lagoon, ember, rose, mono, instrument
    public var label: String {
        switch self {
        case .studio: return "Studio olive"
        case .iris: return "Electric iris"
        case .lagoon: return "Deep lagoon"
        case .ember: return "Warm ember"
        case .rose: return "Wild rose"
        case .mono: return "Monochrome"
        case .instrument: return "Instrument ink"
        }
    }
}

public enum ThemeGround: String, CaseIterable, Sendable {
    case cool, paper, mist
}

public enum CornerProfile: String, CaseIterable, Sendable {
    case square, crisp, soft, round, pill
    public var radii: (small: CGFloat, control: CGFloat, surface: CGFloat, pill: CGFloat) {
        switch self {
${cornerCases}
        }
    }
}

public enum ComponentDensity: String, CaseIterable, Sendable {
    case compact, comfortable, spacious
    public var heights: (xs: CGFloat, small: CGFloat, regular: CGFloat, large: CGFloat, xl: CGFloat) {
        switch self {
${densityCases}
        }
    }
}

public enum ElevationStyle: String, CaseIterable, Sendable {
    case soft, ring
}

struct DynamicSRGB: Sendable {
    let ls: (Double, Double, Double)
    let ds: (Double, Double, Double)
    let lh: (Double, Double, Double)
    let dh: (Double, Double, Double)

    func color() -> Color {
        #if canImport(UIKit)
        return Color(uiColor: UIColor { traits in
            let dark = traits.userInterfaceStyle == .dark
            let high = traits.accessibilityContrast == .high
            let t = dark ? (high ? dh : ds) : (high ? lh : ls)
            return UIColor(red: t.0, green: t.1, blue: t.2, alpha: 1)
        })
        #elseif canImport(AppKit)
        return Color(nsColor: NSColor(name: nil) { appearance in
            let match = appearance.bestMatch(from: [.aqua, .darkAqua, .accessibilityHighContrastAqua, .accessibilityHighContrastDarkAqua])
            let dark = match == .darkAqua || match == .accessibilityHighContrastDarkAqua
            let high = match == .accessibilityHighContrastAqua || match == .accessibilityHighContrastDarkAqua
            let t = dark ? (high ? dh : ds) : (high ? lh : ls)
            return NSColor(srgbRed: t.0, green: t.1, blue: t.2, alpha: 1)
        })
        #else
        return Color(.sRGB, red: ls.0, green: ls.1, blue: ls.2, opacity: 1)
        #endif
    }
}

struct GroundPalette: Sendable {
    let canvas, surface, surfaceLow, surfaceHigh, raised, sunken: DynamicSRGB
    let text, muted, subtle, border, borderStrong: DynamicSRGB
    let success, successSoft, warning, warningSoft, danger, dangerSoft, info, infoSoft: DynamicSRGB
}

struct BrandPalette: Sendable {
    let accent, onAccent, accentHover, accentSoft, onAccentSoft, selection: DynamicSRGB
}

enum GeneratedThemePalettes {
    static let grounds: [ThemeGround: GroundPalette] = [
${groundCases}
    ]
    static let brands: [String: BrandPalette] = [
${brandCases.join(',\n')}
    ]
}
`;
}
